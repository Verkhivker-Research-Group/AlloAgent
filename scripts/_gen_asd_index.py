"""Generate biomni/tool/_asd_index.tsv from the real ASD XF directory.

The old repo shipped a 75 KB Python dict (`alloagent/tool/asd_index.py`).
Committing that dict puts 75 KB of generated data in the source tree; a
two-column TSV does the same job in ~50 KB and loads in milliseconds.

The TSV is derived from the real ASD_Release_202306_XF directory: for
each XML file, the UniProt accession it declares -> the file stem.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))
from _paths import expand_home  # noqa: E402

XF = expand_home(r"<HOME>\Documents\CPSC\Biolab\data\biomni_data\asd\ASD_Release_202306_XF")
OUT = expand_home(r"<HOME>\Documents\CPSC\AlloAgent-v2\biomni\tool\_asd_index.tsv")

PAT = re.compile(rb"<UniProt_ID>([^<]+)</UniProt_ID>")

index: dict[str, str] = {}
files = sorted(XF.glob("*.xml"))
for f in files:
    with open(f, "rb") as fh:
        head = fh.read(4096)
    m = PAT.search(head)
    if m:
        index.setdefault(m.group(1).decode("utf-8").strip(), f.stem)

lines = ["# UniProt accession -> ASD_Release_202306_XF file stem.",
         "# Generated by scripts/_gen_asd_index.py from the real ASD snapshot;",
         "# do not edit by hand.",
         "# uniprot_id\tasd_file_stem"]
for acc in sorted(index):
    lines.append(f"{acc}\t{index[acc]}")
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {OUT} ({len(index)} proteins, {OUT.stat().st_size} bytes) "
      f"from {len(files)} XML files")
if len(sys.argv) > 1:
    print("sample:", list(index.items())[:3])
