"""T5 detect_pockets_p2rank (Part 2).

Wrapper around P2Rank 2.5.1 (rdk/p2rank, GPL-3.0). P2Rank is a Java
tool that runs a conservation-augmented machine-learning classifier
to predict binding pockets from a single PDB or mmCIF file. The
implementation invokes `prank predict -f <input> -o <out_dir>` and
parses the resulting `<input>_predictions.csv` file.

The tool also accepts a manual `pdb_path` argument (the brief uses
"pdb_path" for any mmCIF/PDB input). Output pockets carry the
predicted probability and the residues lining each pocket (chain
+ residue number), sourced from the `<input>_residues.csv` file
generated by `predict`.
"""
from __future__ import annotations

import csv
import os
import shutil
import subprocess
import tempfile
import time
from pathlib import Path
from typing import Any

from biomni.tool._blocklist import benchmark_blocklist
from biomni.tool._netcall import with_return_contract

_TIMEOUT_S = 180


def _utc_now_iso() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def _source() -> str:
    return "P2Rank 2.5.1 (https://github.com/rdk/p2rank)"


def _find_prank() -> str | None:
    return shutil.which("prank")


def _find_java17() -> str | None:
    java_home = os.environ.get("JAVA_HOME")
    if java_home and Path(java_home, "bin", "java").is_file():
        return str(Path(java_home) / "bin" / "java")
    java17 = Path("/usr/lib/jvm/java-17-openjdk-amd64/bin/java")
    if java17.is_file():
        return str(java17)
    return shutil.which("java")


def _prank_output_paths(src: Path, out_dir: Path) -> tuple[Path, Path]:
    """Return (predictions_csv, residues_csv) for a `prank predict`
    run on `src`.  P2Rank 2.5.1 uses the full filename (including
    extension) as the prefix, e.g. `1ake.pdb_predictions.csv`.
    """
    prefix = src.name
    return (
        out_dir / f"{prefix}_predictions.csv",
        out_dir / f"{prefix}_residues.csv",
    )


def _stripped_row(row: dict[str, str]) -> dict[str, str]:
    return {(k or "").strip(): (v or "").strip() for k, v in row.items()}


def _parse_predictions_csv(csv_path: Path) -> list[dict[str, Any]]:
    """Parse `<basename>_predictions.csv` from `prank predict`.

    The CSV column headers are padded with spaces in the
    upstream tool's output (e.g. `' name     '`); this parser
    strips each key/value before reading.

    The CSV has columns: name, rank, score, probability,
    sas_points, surf_atoms, center_x/y/z, residue_ids,
    surf_atom_ids. The pocket name is `<input_stem>:<rank>` in
    the P2Rank 2.5.1 model output.
    """
    if not csv_path.is_file():
        return []
    out: list[dict[str, Any]] = []
    with open(csv_path, "r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for raw_row in reader:
            row = _stripped_row(raw_row)
            try:
                rank = int(row.get("rank", ""))
            except (TypeError, ValueError):
                continue
            try:
                score = float(row.get("score", ""))
            except (TypeError, ValueError):
                score = None
            try:
                prob = float(row.get("probability", ""))
            except (TypeError, ValueError):
                prob = None
            out.append(
                {
                    "rank": rank,
                    "name": row.get("name", ""),
                    "score": score,
                    "probability": prob,
                    "sas_points": row.get("sas_points", ""),
                    "surf_atoms": row.get("surf_atoms", ""),
                    "center_x": row.get("center_x", ""),
                    "center_y": row.get("center_y", ""),
                    "center_z": row.get("center_z", ""),
                }
            )
    return out


def _parse_residues_csv(csv_path: Path) -> dict[int, list[dict[str, str]]]:
    """Parse `<basename>_residues.csv` and group residues by pocket rank.
    Returns {rank: [{"residue_number": <str>, "chain": <str>, ...}, ...]}.
    """
    if not csv_path.is_file():
        return {}
    by_rank: dict[int, list[dict[str, str]]] = {}
    with open(csv_path, "r", encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        for raw_row in reader:
            row = _stripped_row(raw_row)
            try:
                rank = int(row.get("pocket", ""))
            except (TypeError, ValueError):
                continue
            by_rank.setdefault(rank, []).append(
                {
                    "chain": row.get("chain", ""),
                    "residue_label": row.get("residue_label", ""),
                    "residue_name": row.get("residue_name", ""),
                    "score": row.get("score", ""),
                    "probability": row.get("probability", ""),
                }
            )
    return by_rank


@with_return_contract(source_version="1.0")
@benchmark_blocklist
def detect_pockets_p2rank(pdb_path):
    """Run P2Rank 2.5.1 `predict` on a PDB or mmCIF file and return
    the predicted pockets.

    Parameters
    ----------
    pdb_path : str or Path
        Path to a PDB or mmCIF file. P2Rank accepts both.

    Returns
    -------
    dict
        Contract dict
        ``{success, data, error, source, source_version,
        query_time_utc}``. ``data`` is::

            {
                "pdb_id": <file stem>,
                "pockets": [
                    {"rank": <int>, "score": <float>,
                     "probability": <float>,
                     "residues": [{"residue_number": <str>,
                                  "chain": <str>, ...}, ...]},
                    ...
                ],
                "runtime_s": <float>,
                "p2rank_exit_code": <int>
            }
    """
    src = Path(pdb_path)
    if not src.is_file():
        return {
            "success": False,
            "data": None,
            "error": f"PDB path does not exist: {src}",
        }

    prank = _find_prank()
    if prank is None:
        return {
            "success": False,
            "data": None,
            "error": "prank launcher not found on PATH",
        }
    java = _find_java17()
    if java is None:
        return {
            "success": False,
            "data": None,
            "error": "java runtime not found (need Java 17 for P2Rank 2.5.1)",
        }

    tmp_dir: tempfile.TemporaryDirectory | None = None
    try:
        tmp_dir = tempfile.TemporaryDirectory(
            prefix="alloagent_p2rank_", dir="/tmp"
        )
        out_dir = Path(tmp_dir.name) / "p2rank_out"

        t0 = time.perf_counter()
        try:
            proc = subprocess.run(
                [prank, "predict", "-f", str(src), "-o", str(out_dir)],
                capture_output=True,
                text=True,
                timeout=_TIMEOUT_S,
            )
        except subprocess.TimeoutExpired:
            return {
                "success": False,
                "data": None,
                "error": f"prank predict timed out after {_TIMEOUT_S}s",
            }
        runtime_s = time.perf_counter() - t0

        predictions_csv, residues_csv = _prank_output_paths(src, out_dir)

        predictions = _parse_predictions_csv(predictions_csv)
        residues_by_rank = _parse_residues_csv(residues_csv)

        pockets = []
        for p in predictions:
            rank = p["rank"]
            pockets.append(
                {
                    "rank": rank,
                    "name": p["name"],
                    "score": p["score"],
                    "probability": p["probability"],
                    "residues": residues_by_rank.get(rank, []),
                }
            )

        return {
            "success": True,
            "data": {
                "pdb_id": src.stem,
                "pockets": pockets,
                "runtime_s": round(runtime_s, 3),
                "p2rank_exit_code": proc.returncode,
            },
        }
    finally:
        if tmp_dir is not None:
            tmp_dir.cleanup()